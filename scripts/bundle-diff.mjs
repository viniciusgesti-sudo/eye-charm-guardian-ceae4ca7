#!/usr/bin/env node
/**
 * Bundle DIFF report vs baseline.
 *
 * Emits `reports/bundle-diff.json` and `reports/bundle-diff.html` describing
 * how the CURRENT build compares to a previously captured baseline, at both
 * chunk and (when sourcemaps are available) module granularity.
 *
 * Usage:
 *   bun run build                          # normal build (no sourcemaps)
 *   BUNDLE_STATS=1 bun run build          # build with hidden sourcemaps
 *   node scripts/bundle-diff.mjs          # write reports vs baseline
 *   node scripts/bundle-diff.mjs --update-baseline
 *
 * Baseline file: `bundle-stats.baseline.json` (chunk + module sizes).
 *
 * When sourcemaps are absent, the per-module section is omitted and only
 * chunk-level diffs are produced. That keeps normal CI fast; run with
 * `BUNDLE_STATS=1` locally when investigating growth.
 */
import { readdirSync, statSync, existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";
import { canonicalBuildPath, resolveBuildOutput } from "./build-output.mjs";

const ROOT = process.cwd();
const BUILD_OUTPUT = resolveBuildOutput(ROOT);
const CLIENT_DIR = BUILD_OUTPUT.clientDir;
const SERVER_DIR = BUILD_OUTPUT.serverDir;
const REPORTS_DIR = join(ROOT, "reports");
const BASELINE_PATH = join(ROOT, "bundle-stats.baseline.json");

const UPDATE = process.argv.includes("--update-baseline");

// -------- fs walk --------
function walk(dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

// -------- VLQ decoder (source-map v3) --------
const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const B64_IDX = new Int8Array(128).fill(-1);
for (let i = 0; i < B64.length; i++) B64_IDX[B64.charCodeAt(i)] = i;

function decodeVLQ(str) {
  const out = [];
  let value = 0;
  let shift = 0;
  for (let i = 0; i < str.length; i++) {
    const d = B64_IDX[str.charCodeAt(i)];
    if (d < 0) continue;
    const cont = d & 32;
    value |= (d & 31) << shift;
    if (cont) {
      shift += 5;
    } else {
      const negative = value & 1;
      value >>= 1;
      out.push(negative ? -value : value);
      value = 0;
      shift = 0;
    }
  }
  return out;
}

/**
 * Attribute generated bytes of `code` to each source in the sourcemap.
 * Approximation: for each mapping segment, count the number of characters
 * from that segment's generated column to the next segment's start.
 * Matches the source-map-explorer heuristic and is stable enough for diffs.
 */
function attributeBytes(code, mapJson) {
  const { sources = [], mappings = "" } = mapJson;
  const perSource = new Map();
  const lines = code.split("\n");
  const segLines = mappings.split(";");
  let srcIdx = 0; // absolute source index (delta-encoded across all segments)

  for (let l = 0; l < segLines.length; l++) {
    const line = lines[l] ?? "";
    const segs = segLines[l];
    if (!segs) continue;
    const raw = segs.split(",");
    // Decode all segments on this line, tracking generated column and source index.
    let genCol = 0;
    const decoded = [];
    for (const seg of raw) {
      if (!seg) continue;
      const v = decodeVLQ(seg);
      genCol += v[0];
      if (v.length >= 4) srcIdx += v[1];
      decoded.push({ genCol, src: v.length >= 4 ? srcIdx : null });
    }
    for (let i = 0; i < decoded.length; i++) {
      const cur = decoded[i];
      const next = decoded[i + 1];
      const end = next ? next.genCol : line.length;
      const bytes = Math.max(0, end - cur.genCol);
      if (cur.src == null) continue;
      const name = sources[cur.src] ?? `<${cur.src}>`;
      perSource.set(name, (perSource.get(name) ?? 0) + bytes);
    }
  }
  return perSource;
}

// -------- Collect chunks + modules --------
function collectChunks(dir, side) {
  const files = walk(dir).filter((f) => /\.(m?js|css)$/.test(f) && !f.endsWith(".map"));
  const chunks = [];
  for (const f of files) {
    const size = statSync(f).size;
    const rel = canonicalBuildPath(BUILD_OUTPUT, f, side);
    const chunk = { path: rel, size, modules: null };
    // Try inline sourcemap ref, then .map file
    let mapPath = f + ".map";
    if (!existsSync(mapPath)) mapPath = null;
    if (mapPath) {
      try {
        const code = readFileSync(f, "utf8");
        const map = JSON.parse(readFileSync(mapPath, "utf8"));
        const attrib = attributeBytes(code, map);
        const modules = {};
        for (const [src, bytes] of attrib) {
          // Normalize path: strip leading ../, resolve to project-relative.
          const clean = src.replace(/^\.\.\//, "").replace(/\?.*$/, "");
          modules[clean] = (modules[clean] ?? 0) + bytes;
        }
        chunk.modules = modules;
      } catch (err) {
        chunk.modulesError = String(err.message || err);
      }
    }
    chunks.push(chunk);
  }
  return chunks;
}

function normalizeChunkKey(relPath) {
  // Strip Vite/Rollup content hash: `Foo-abcd1234.js` → `Foo.js`.
  // Only strip 8-char hashes preceded by a dash right before the extension.
  return relPath.replace(/-[A-Za-z0-9_-]{8,12}(\.[cm]?js|\.css|\.mjs)$/, "$1");
}

function summarize(chunks) {
  const total = chunks.reduce((n, c) => n + c.size, 0);
  const byPath = {};
  for (const c of chunks) {
    const key = normalizeChunkKey(c.path);
    if (byPath[key]) {
      // Merge duplicates (rare, e.g. same-name chunk in different subdirs).
      byPath[key].size += c.size;
      if (c.modules) {
        byPath[key].modules = byPath[key].modules ?? {};
        for (const [k, v] of Object.entries(c.modules))
          byPath[key].modules[k] = (byPath[key].modules[k] ?? 0) + v;
      }
    } else {
      byPath[key] = { ...c, path: key };
    }
  }
  return { total, byPath };
}

const current = {
  version: 1,
  capturedAt: new Date().toISOString(),
  hasSourcemaps: process.env.BUNDLE_STATS === "1",
  provider: BUILD_OUTPUT.provider,
  client: summarize(collectChunks(CLIENT_DIR, "client")),
  server: summarize(collectChunks(SERVER_DIR, "server")),
};

if (UPDATE) {
  writeFileSync(BASELINE_PATH, JSON.stringify(current, null, 2));
  console.log(`[bundle-diff] baseline updated → ${relative(ROOT, BASELINE_PATH)}`);
  process.exit(0);
}

if (!existsSync(BASELINE_PATH)) {
  console.warn(
    `[bundle-diff] no baseline at ${relative(ROOT, BASELINE_PATH)}. ` +
      `Run with --update-baseline to create one.`,
  );
  writeFileSync(BASELINE_PATH, JSON.stringify(current, null, 2));
  console.log("[bundle-diff] wrote initial baseline; nothing to diff.");
  process.exit(0);
}

const baseline = JSON.parse(readFileSync(BASELINE_PATH, "utf8"));

// -------- Diff logic --------
function fmtBytes(n) {
  if (n == null) return "—";
  const sign = n < 0 ? "-" : "";
  const abs = Math.abs(n);
  if (abs < 1024) return `${sign}${abs} B`;
  if (abs < 1024 * 1024) return `${sign}${(abs / 1024).toFixed(1)} KB`;
  return `${sign}${(abs / 1024 / 1024).toFixed(2)} MB`;
}
function pct(cur, base) {
  if (!base) return cur ? Infinity : 0;
  return ((cur - base) / base) * 100;
}
function classify(cur, base) {
  if (base == null) return "added";
  if (cur == null) return "removed";
  if (cur === base) return "same";
  return cur > base ? "grew" : "shrank";
}

function diffMap(curMap, baseMap) {
  const keys = new Set([...Object.keys(curMap ?? {}), ...Object.keys(baseMap ?? {})]);
  const rows = [];
  for (const k of keys) {
    const cur = curMap?.[k];
    const base = baseMap?.[k];
    const delta = (cur ?? 0) - (base ?? 0);
    rows.push({
      key: k,
      current: cur ?? null,
      baseline: base ?? null,
      delta,
      deltaPct: base != null && cur != null ? pct(cur, base) : null,
      status: classify(cur, base),
    });
  }
  rows.sort((a, b) => Math.abs(b.delta) - Math.abs(a.delta));
  return rows;
}

function diffBundle(cur, base) {
  const curBy = cur?.byPath ?? {};
  const baseBy = base?.byPath ?? {};
  const chunkRows = [];
  const keys = new Set([...Object.keys(curBy), ...Object.keys(baseBy)]);
  for (const k of keys) {
    const c = curBy[k];
    const b = baseBy[k];
    const curSize = c?.size ?? null;
    const baseSize = b?.size ?? null;
    const delta = (curSize ?? 0) - (baseSize ?? 0);
    const moduleDiff =
      c?.modules || b?.modules
        ? diffMap(c?.modules, b?.modules).filter((r) => r.delta !== 0)
        : null;
    chunkRows.push({
      chunk: k,
      current: curSize,
      baseline: baseSize,
      delta,
      deltaPct: baseSize != null && curSize != null ? pct(curSize, baseSize) : null,
      status: classify(curSize, baseSize),
      moduleDiff,
    });
  }
  chunkRows.sort((a, b) => Math.abs(b.delta) - Math.abs(a.delta));
  const curTotal = cur?.total ?? 0;
  const baseTotal = base?.total ?? 0;
  return {
    totals: {
      current: curTotal,
      baseline: baseTotal,
      delta: curTotal - baseTotal,
      deltaPct: pct(curTotal, baseTotal),
    },
    chunks: chunkRows,
  };
}

const diff = {
  version: 1,
  generatedAt: new Date().toISOString(),
  baselineCapturedAt: baseline.capturedAt,
  hasSourcemaps: current.hasSourcemaps && baseline.hasSourcemaps,
  client: diffBundle(current.client, baseline.client),
  server: diffBundle(current.server, baseline.server),
};

// -------- Write JSON + HTML --------
mkdirSync(REPORTS_DIR, { recursive: true });
const jsonPath = join(REPORTS_DIR, "bundle-diff.json");
const htmlPath = join(REPORTS_DIR, "bundle-diff.html");
writeFileSync(jsonPath, JSON.stringify(diff, null, 2));

function statusBadge(s) {
  const map = {
    added: ["#0a7", "NEW"],
    removed: ["#888", "GONE"],
    grew: ["#c33", "▲"],
    shrank: ["#0a7", "▼"],
    same: ["#999", "="],
  };
  const [color, label] = map[s] ?? ["#999", s];
  return `<span style="background:${color};color:#fff;padding:2px 6px;border-radius:4px;font-size:11px;font-weight:600">${label}</span>`;
}

function renderRow(r) {
  const deltaColor = r.delta > 0 ? "#c33" : r.delta < 0 ? "#0a7" : "#666";
  const pctTxt =
    r.deltaPct == null || !isFinite(r.deltaPct)
      ? "—"
      : `${r.deltaPct >= 0 ? "+" : ""}${r.deltaPct.toFixed(1)}%`;
  return `<tr>
    <td>${statusBadge(r.status)}</td>
    <td style="font-family:ui-monospace,monospace;font-size:12px">${r.chunk || r.key}</td>
    <td style="text-align:right">${fmtBytes(r.current)}</td>
    <td style="text-align:right;color:#666">${fmtBytes(r.baseline)}</td>
    <td style="text-align:right;color:${deltaColor};font-weight:600">${r.delta > 0 ? "+" : ""}${fmtBytes(r.delta)}</td>
    <td style="text-align:right;color:${deltaColor}">${pctTxt}</td>
  </tr>`;
}

function renderModuleSection(rows) {
  if (!rows || rows.length === 0) return "";
  const top = rows.slice(0, 40);
  return `<details style="margin:8px 0 16px 24px"><summary style="cursor:pointer;color:#555;font-size:12px">${rows.length} module change(s) — show top ${top.length}</summary>
    <table style="width:100%;border-collapse:collapse;margin-top:6px;font-size:12px">
      <thead><tr style="background:#f4f4f4"><th></th><th style="text-align:left">module</th><th style="text-align:right">current</th><th style="text-align:right">baseline</th><th style="text-align:right">Δ</th><th style="text-align:right">Δ%</th></tr></thead>
      <tbody>${top.map((m) => renderRow({ ...m, chunk: m.key })).join("")}</tbody>
    </table></details>`;
}

function renderBundle(name, b) {
  const t = b.totals;
  const deltaColor = t.delta > 0 ? "#c33" : t.delta < 0 ? "#0a7" : "#666";
  const changed = b.chunks.filter((c) => c.delta !== 0);
  return `<section style="margin:24px 0">
    <h2 style="margin:0 0 8px">${name}</h2>
    <p style="margin:0 0 12px;color:#333">
      Total: <b>${fmtBytes(t.current)}</b>
      (baseline ${fmtBytes(t.baseline)},
      <span style="color:${deltaColor};font-weight:600">${t.delta >= 0 ? "+" : ""}${fmtBytes(t.delta)} / ${t.deltaPct >= 0 ? "+" : ""}${t.deltaPct.toFixed(1)}%</span>)
    </p>
    <table style="width:100%;border-collapse:collapse;font-size:13px">
      <thead><tr style="background:#eee">
        <th></th><th style="text-align:left">chunk</th>
        <th style="text-align:right">current</th><th style="text-align:right">baseline</th>
        <th style="text-align:right">Δ</th><th style="text-align:right">Δ%</th>
      </tr></thead>
      <tbody>
        ${changed.map((c) => renderRow(c) + (c.moduleDiff ? `<tr><td colspan="6" style="padding:0">${renderModuleSection(c.moduleDiff)}</td></tr>` : "")).join("")}
      </tbody>
    </table>
    ${changed.length === 0 ? '<p style="color:#0a7">No chunk changes.</p>' : ""}
  </section>`;
}

const html = `<!doctype html><html><head><meta charset="utf-8">
<title>Bundle diff — ${diff.generatedAt}</title>
<style>
  body{font:14px/1.5 system-ui,-apple-system,Segoe UI,sans-serif;max-width:1200px;margin:24px auto;padding:0 16px;color:#111}
  table{border-collapse:collapse}
  th,td{padding:6px 10px;border-bottom:1px solid #eee}
  h1{margin:0 0 4px}
  .meta{color:#666;font-size:12px;margin-bottom:16px}
</style></head><body>
<h1>Bundle diff</h1>
<div class="meta">
  Generated ${diff.generatedAt} — baseline ${diff.baselineCapturedAt} —
  per-module attribution: <b>${diff.hasSourcemaps ? "ON" : "OFF (run with BUNDLE_STATS=1 for module diff)"}</b>
</div>
${renderBundle("Client", diff.client)}
${renderBundle("Server", diff.server)}
</body></html>`;

writeFileSync(htmlPath, html);
console.log(`[bundle-diff] wrote ${relative(ROOT, jsonPath)}`);
console.log(`[bundle-diff] wrote ${relative(ROOT, htmlPath)}`);
console.log(
  `[bundle-diff] client Δ ${fmtBytes(diff.client.totals.delta)} (${diff.client.totals.deltaPct.toFixed(1)}%) · ` +
    `server Δ ${fmtBytes(diff.server.totals.delta)} (${diff.server.totals.deltaPct.toFixed(1)}%)`,
);
